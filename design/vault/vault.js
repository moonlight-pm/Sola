function icon(name, size = 14, sw = 1.75) {
  return `<svg class="ic" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] || ""}</svg>`;
}

function drawIcons(root = document) {
  root.querySelectorAll("i[data-i]").forEach((el) => {
    el.outerHTML = icon(el.dataset.i, Number(el.dataset.s || 14), Number(el.dataset.w || 1.75));
  });
}

/* The ring: an arc for the seconds left of 30, warning under 6. */
function drawRing(el, left) {
  const period = Number(el.dataset.period || 30);
  const r = 9, c = 2 * Math.PI * r;
  const frac = left / period;
  const tone = left <= 5 ? "var(--warning)" : "var(--ink-2)";
  el.innerHTML =
    `<svg width="22" height="22" viewBox="0 0 22 22">` +
    `<circle cx="11" cy="11" r="${r}" fill="none" stroke="var(--hairline-strong)" stroke-width="2"/>` +
    `<circle cx="11" cy="11" r="${r}" fill="none" stroke="${tone}" stroke-width="2" stroke-linecap="round"` +
    ` stroke-dasharray="${(c * frac).toFixed(2)} ${c.toFixed(2)}"/></svg><b style="color:${tone}">${left}</b>`;
}

function runRings() {
  const rings = [...document.querySelectorAll(".ring[data-left]")];
  rings.forEach((el) => drawRing(el, Number(el.dataset.left)));
  if (!rings.length) return;
  setInterval(() => {
    rings.forEach((el) => {
      let left = Number(el.dataset.left) - 1;
      if (left < 1) left = Number(el.dataset.period || 30);
      el.dataset.left = String(left);
      drawRing(el, left);
    });
  }, 1000);
}

document.addEventListener("DOMContentLoaded", () => {
  drawIcons();
  runRings();
});
