//! An Oath plan for one of Sola's packages: the header (`build_needs` and
//! `run_needs`, each pinned by hash) and the script `oath build` runs in
//! its sandbox (no network; only the build_needs packs, at
//! `/oath/store/pkg/<name>/<hash>/`, each with a `live` link).
//!
//! The script builds from `pkg:sola-src` (the tree at `src/sola`, the
//! icon and cursor packs at `src/share`) against `pkg:sola-crates`, and
//! lays out `/out` as `cargo make oath stage` does.

use super::packages::Package;

pub struct Inputs<'a> {
    pub pkg: &'a Package,
    /// `(id, hash)`; `pkg:sola-src` and `pkg:sola-crates` among them.
    pub build_needs: Vec<(String, String)>,
    pub run_needs: Vec<(String, String)>,
    pub src_hash: &'a str,
    pub crates_hash: &'a str,
    /// For `components.json`.
    pub version: &'a str,
}

const OATH_CEF: &str = "/oath/store/pkg/cef/live/cef";

/// The plan's text. `oath fmt` makes it canonical before it is filed.
pub fn text(i: &Inputs) -> String {
    let needs = |v: &[(String, String)]| {
        let mut v = v.to_vec();
        v.sort();
        v.dedup();
        serde_json::Value::Array(
            v.into_iter()
                .map(|(id, hash)| serde_json::json!({ "id": id, "hash": hash }))
                .collect(),
        )
    };
    let header = serde_json::json!({
        "name": i.pkg.name,
        "produces": i.pkg.id(),
        "build_needs": needs(&i.build_needs),
        "run_needs": needs(&i.run_needs),
    });
    format!(
        "#!oath-plan\n{}\n---\n{}",
        serde_json::to_string_pretty(&header).expect("plan header"),
        script(i)
    )
}

fn script(i: &Inputs) -> String {
    let p = i.pkg;
    let mut s = String::new();
    s += "#!/bin/sh\nset -eu\n";
    s += &format!("# generated by `cargo make oath publish` ({})\n", i.version);
    s += &format!("SRC=/oath/store/pkg/sola-src/{}/src\n", i.src_hash);
    s += &format!("CRATES=/oath/store/pkg/sola-crates/{}\n", i.crates_hash);
    s += "export CC=cc CXX=c++ AR=ar RANLIB=ranlib NM=nm STRIP=strip\n";
    s += "export CFLAGS=\"-O2 -pipe\" CXXFLAGS=\"-O2 -pipe\" SOURCE_DATE_EPOCH=0\n";
    // RUSTFLAGS replaces .cargo/config.toml's NixOS rpaths.
    s += "export CARGO_HOME=/tmp/cargo HOME=/tmp/home\n";
    s += "export RUSTFLAGS=\"-C link-arg=-Wl,--enable-new-dtags\"\n";
    s += "mkdir -p \"$CARGO_HOME\" \"$HOME/.cache/sola\"\n";
    s += "sed \"s|@VENDOR@|$CRATES/vendor|\" \"$CRATES/vendor.toml\" >\"$CARGO_HOME/config.toml\"\n";
    s += "cp -R \"$SRC/sola\" /tmp/sola\n";
    s += "cd /tmp/sola\n";
    if p.cef {
        s += &format!("export SOLA_CEF_DIR={OATH_CEF}\n");
        s += "ln -s \"$SOLA_CEF_DIR\" \"$HOME/.cache/sola/cef-$(cat cef-version)\"\n";
    }
    let crates: Vec<String> = p.bins.iter().map(|b| format!("-p {b}")).collect();
    s += &format!("cargo build --release --frozen {}\n", crates.join(" "));
    s += "mkdir -p /out/bin\n";
    s += &format!(
        "for b in {}; do cp \"target/release/$b\" /out/bin/; done\n",
        p.bins.join(" ")
    );
    if p.share {
        s += "cp -R \"$SRC/share\" /out/share\n";
    }
    if p.cef {
        s += &format!("ln -s {OATH_CEF} /out/cef\n");
    }
    s += &format!(
        "printf '%s\\n' '[{{\"name\":\"{n}\",\"purl\":\"pkg:generic/{n}@{v}\",\"version\":\"{v}\"}}]' >/out/components.json\n",
        n = p.name,
        v = i.version
    );
    s
}

#[cfg(test)]
mod tests {
    use super::super::packages::PACKAGES;
    use super::*;

    #[test]
    fn browser_plan_links_cef_and_pins_its_sources() {
        let pkg = &PACKAGES[1];
        let t = text(&Inputs {
            pkg,
            build_needs: vec![("pkg:rust".into(), "sha256-r".into())],
            run_needs: vec![("pkg:cef".into(), "sha256-c".into())],
            src_hash: "sha256-s",
            crates_hash: "sha256-k",
            version: "0.1.0+gabc",
        });
        assert!(t.starts_with("#!oath-plan\n{"));
        assert!(t.contains("\n---\n#!/bin/sh\nset -eu\n"));
        assert!(t.contains("\"produces\": \"pkg:sola-browser\""));
        assert!(t.contains("SRC=/oath/store/pkg/sola-src/sha256-s/src"));
        assert!(t.contains("cargo build --release --frozen -p sola-browser"));
        assert!(t.contains("ln -s /oath/store/pkg/cef/live/cef /out/cef"));
        assert!(!t.contains("$SRC/share"));
    }
}
