//! Oath plans for Sola's packages: a header (`build_needs` and
//! `run_needs`, each pinned by hash) and the script `oath build` runs in
//! its sandbox (no network; only the build_needs packs, at
//! `/oath/store/pkg/<name>/<hash>/`, each with a `live` link).
//!
//! One plan compiles: `plan:sola-build` builds every package's programs
//! in a single `cargo build` from `pkg:sola-src` (the tree at
//! `src/sola`, the icon and cursor packs at `src/share`) against
//! `pkg:sola-crates`, into `bin/`. Each package's plan then only lays
//! out `/out` from that build (and, for `pkg:sola`, the share tree), as
//! `cargo make oath stage` does.

use super::packages::Package;

/// The package the compile plan produces: a build pack, never linked.
pub const BUILD: &str = "sola-build";

pub struct Plan {
    pub name: String,
    /// `(id, hash)`.
    pub build_needs: Vec<(String, String)>,
    pub run_needs: Vec<(String, String)>,
    pub script: String,
}

const OATH_CEF: &str = "/oath/store/pkg/cef/live/cef";

/// The plan's text. `oath fmt` makes it canonical before it is filed.
pub fn text(p: &Plan) -> String {
    let needs = |v: &[(String, String)]| {
        let mut v = v.to_vec();
        v.sort();
        v.dedup();
        serde_json::Value::Array(
            v.into_iter()
                .map(|(id, hash)| serde_json::json!({ "id": id, "hash": hash }))
                .collect(),
        )
    };
    let header = serde_json::json!({
        "name": p.name,
        "produces": format!("pkg:{}", p.name),
        "build_needs": needs(&p.build_needs),
        "run_needs": needs(&p.run_needs),
    });
    format!(
        "#!oath-plan\n{}\n---\n{}",
        serde_json::to_string_pretty(&header).expect("plan header"),
        p.script
    )
}

/// `plan:sola-build`: every program in `bins`, one release build.
pub fn build_script(bins: &[&str], src_hash: &str, crates_hash: &str, version: &str) -> String {
    let mut s = prologue(version);
    s += &format!("SRC=/oath/store/pkg/sola-src/{src_hash}/src\n");
    s += &format!("CRATES=/oath/store/pkg/sola-crates/{crates_hash}\n");
    s += "export CC=cc CXX=c++ AR=ar RANLIB=ranlib NM=nm STRIP=strip\n";
    s += "export CFLAGS=\"-O2 -pipe\" CXXFLAGS=\"-O2 -pipe\" SOURCE_DATE_EPOCH=0\n";
    // RUSTFLAGS replaces .cargo/config.toml's NixOS rpaths.
    s += "export CARGO_HOME=/tmp/cargo HOME=/tmp/home\n";
    s += "export RUSTFLAGS=\"-C link-arg=-Wl,--enable-new-dtags\"\n";
    s += "mkdir -p \"$CARGO_HOME\" \"$HOME/.cache/sola\"\n";
    s += "sed \"s|@VENDOR@|$CRATES/vendor|\" \"$CRATES/vendor.toml\" >\"$CARGO_HOME/config.toml\"\n";
    s += "cp -R \"$SRC/sola\" /tmp/sola\n";
    s += "cd /tmp/sola\n";
    // The CEF programs link pkg:cef and name its Release/ in RUNPATH.
    s += &format!("export SOLA_CEF_DIR={OATH_CEF}\n");
    s += "ln -s \"$SOLA_CEF_DIR\" \"$HOME/.cache/sola/cef-$(cat cef-version)\"\n";
    let crates: Vec<String> = bins.iter().map(|b| format!("-p {b}")).collect();
    s += &format!("cargo build --release --frozen {}\n", crates.join(" "));
    s += "mkdir -p /out/bin\n";
    s += &format!(
        "for b in {}; do cp \"target/release/$b\" /out/bin/; done\n",
        bins.join(" ")
    );
    s += &components(BUILD, version);
    s
}

/// A package's plan: its programs from `pkg:sola-build`, its share tree
/// from `pkg:sola-src`, its `cef` link.
pub fn package_script(pkg: &Package, build_hash: &str, src_hash: &str, version: &str) -> String {
    let mut s = prologue(version);
    s += &format!("BUILD=/oath/store/pkg/{BUILD}/{build_hash}\n");
    s += "mkdir -p /out/bin\n";
    s += &format!(
        "for b in {}; do cp \"$BUILD/bin/$b\" /out/bin/; done\n",
        pkg.bins.join(" ")
    );
    if pkg.share {
        s += &format!("cp -R /oath/store/pkg/sola-src/{src_hash}/src/share /out/share\n");
    }
    if pkg.cef {
        s += &format!("ln -s {OATH_CEF} /out/cef\n");
    }
    s += &components(pkg.name, version);
    s
}

fn prologue(version: &str) -> String {
    format!("#!/bin/sh\nset -eu\n# generated by `cargo make oath publish` ({version})\n")
}

fn components(name: &str, version: &str) -> String {
    format!(
        "printf '%s\\n' '[{{\"name\":\"{name}\",\"purl\":\"pkg:generic/{name}@{version}\",\"version\":\"{version}\"}}]' >/out/components.json\n"
    )
}

#[cfg(test)]
mod tests {
    use super::super::packages::PACKAGES;
    use super::*;

    #[test]
    fn one_build_compiles_every_program() {
        let bins: Vec<&str> = PACKAGES.iter().flat_map(|p| p.bins.iter().copied()).collect();
        let s = build_script(&bins, "sha256-s", "sha256-k", "0.1.0+gabc");
        assert!(s.starts_with("#!/bin/sh\nset -eu\n"));
        assert!(s.contains("SRC=/oath/store/pkg/sola-src/sha256-s/src"));
        assert!(s.contains("-p sola-shell") && s.contains("-p sola-browser"));
        assert_eq!(s.matches("cargo build").count(), 1);
    }

    #[test]
    fn browser_plan_copies_its_program_and_links_cef() {
        let pkg = &PACKAGES[1];
        let t = text(&Plan {
            name: pkg.name.into(),
            build_needs: vec![("pkg:sola-build".into(), "sha256-b".into())],
            run_needs: vec![("pkg:cef".into(), "sha256-c".into())],
            script: package_script(pkg, "sha256-b", "sha256-s", "0.1.0+gabc"),
        });
        assert!(t.starts_with("#!oath-plan\n{"));
        assert!(t.contains("\n---\n#!/bin/sh\nset -eu\n"));
        assert!(t.contains("\"produces\": \"pkg:sola-browser\""));
        assert!(t.contains("BUILD=/oath/store/pkg/sola-build/sha256-b"));
        assert!(t.contains("ln -s /oath/store/pkg/cef/live/cef /out/cef"));
        assert!(!t.contains("cargo build") && !t.contains("/src/share"));
    }
}
